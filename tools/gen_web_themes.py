#!/usr/bin/env python3
"""Writes web/js/themes.js from the Android app's themes (Appearance.kt and the English strings), so the web
version has exactly the same colours. Run it from the repository root after changing a theme."""
import re, json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
kt = (root / "app/src/main/java/it/sunw/widget/Appearance.kt").read_text()
strings = (root / "app/src/main/res/values/strings.xml").read_text()
names = dict(re.findall(r'<string name="([a-z_0-9]+)">(.*?)</string>', strings))

def argb(h):
    v = int(h, 16)
    return "#%06X" % (v & 0xFFFFFF), (v >> 24) & 0xFF

def color(h):
    c, a = argb(h)
    return c if a == 255 else "rgba(%d,%d,%d,%.3f)" % (int(c[1:3], 16), int(c[3:5], 16), int(c[5:7], 16), a / 255)

# --- the enum: key, label string, light
enum_body = kt[kt.index("enum class Theme("):kt.index("    /** Rounded (system radius)")]
entries = re.findall(r'([A-Z_0-9]+)\("([a-z_0-9]+)", R\.string\.([a-z_0-9]+)(, isLight = true)?\)', enum_body)
order = [e[0] for e in entries]

# --- groups
group_body = enum_body[enum_body.index("val group: ThemeGroup"):]
groups = {}
for names_part, g in re.findall(r'((?:[A-Z_0-9]+(?:, )?)+) -> ThemeGroup\.([A-Z_]+)', group_body):
    for n in re.findall(r'[A-Z_0-9]+', names_part):
        groups[n] = g
group_titles = {g: names.get("theme_group_" + g.lower(), g) for g in
                ["SYSTEM", "COMMUNITY_DARK", "COMMUNITY_LIGHT", "ORIGINAL_DARK", "ORIGINAL_LIGHT", "MINIMALIST"]}
group_titles = {
    "SYSTEM": "System", "COMMUNITY_DARK": "Community – dark", "COMMUNITY_LIGHT": "Community – light",
    "ORIGINAL_DARK": "Originals – dark", "ORIGINAL_LIGHT": "Originals – light", "MINIMALIST": "Minimalist",
}
group_of = lambda n: "LEGACY" if n == "ANTHRACITE" else groups.get(n, "MINIMALIST")

# --- sky ramps
def parse_sky_list(text):
    return [color(h) for h in re.findall(r"0x([0-9A-Fa-f]{8})", text)]

default_sky = parse_sky_list(kt[kt.index("private val SKY = listOf("):kt.index("/** The same progression drawn from the Tokyo Night")])
tokyo_sky = parse_sky_list(kt[kt.index("private val TOKYO_SKY"):kt.index("    }\n}", kt.index("private val TOKYO_SKY"))])
stops = [-18, -12, -6, -2, 1, 6, 15, 30]

themes = {}
for m in re.finditer(r"Theme\.([A-Z_0-9]+) -> Palette\((.*?)\n            \)", kt, re.S):
    name, body = m.group(1), m.group(2)
    def arg(k):
        mm = re.search(k + r" = 0x([0-9A-Fa-f]{8})", body)
        return color(mm.group(1))
    sky = re.search(r"sky = (sky\((.*?)\)|TOKYO_SKY)", body, re.S)
    ramp = tokyo_sky if sky.group(1) == "TOKYO_SKY" else parse_sky_list(sky.group(2))
    themes[name] = dict(background=arg("background"), text=arg("text"), textSecondary=arg("textSecondary"), dim=arg("dim"),
                        page=arg("pageBackground"), card=arg("cardBackground"), sky=ramp, blueHour=arg("blueHour"),
                        goldenHour=arg("goldenHour"), highSun=arg("highSun"), twilightBand=arg("twilightBand"))

# the four built on the default palette
base = dict(text="#F2F1EE", textSecondary="#A8A6A1", dim="#7D7B77", page="#121316", card="#1B1C20", sky=default_sky,
            blueHour="#5B8CFF", goldenHour="#FF8A2A", highSun="#FFE3A0", twilightBand="#7F8CFF")
themes["ANTHRACITE"] = dict(base, background="rgba(20,21,24,0.902)")
themes["BLACK"] = dict(base, background="#000000", page="#000000")
themes["GLASS"] = dict(base, background="rgba(20,21,24,0.502)")
themes["MATERIAL_YOU"] = dict(base, background="rgba(20,21,24,0.902)")  # no system colours on the web: the default

out = []
for name, key, label, light in entries:
    t = themes[name]
    out.append(dict(key=key, name=names.get(label, key), light=bool(light), group=group_of(name),
                    **{k: t[k] for k in ("background", "text", "textSecondary", "dim", "page", "card", "sky", "blueHour", "goldenHour", "highSun", "twilightBand")}))

js = "// Generated by tools/gen_web_themes.py from the Android app's Appearance.kt: do not edit by hand.\n"
js += "export const SKY_STOPS = %s;\n" % json.dumps(stops)
js += "export const GROUP_TITLES = %s;\n" % json.dumps(group_titles, ensure_ascii=False)
js += "export const THEMES = %s;\n" % json.dumps(out, ensure_ascii=False, indent=1)
(root / "web/js/themes.js").write_text(js)
print(len(out), "themes")
